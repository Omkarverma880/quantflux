def sector_of(symbol: str) -> str:
    return SECTOR_MAP.get((symbol or "").strip().upper(), "Other")


def group_by_sector(rows: list[dict], key: str = "symbol") -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for r in rows:
        out.setdefault(sector_of(r.get(key, "")), []).append(r)
    return out
